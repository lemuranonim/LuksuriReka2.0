import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

// Compile the repository-owned SVG artwork into a Server Component. The static
// composition is sent in the HTML, including when JavaScript or assets fail.
export function buildExperiencePosters() {
  const kinds = ["identity", "solutions", "work"];
  const branches = kinds.map(kind => {
    const svg = readFileSync(new URL(`../public/experience/${kind}-poster.svg`, import.meta.url), "utf8");
    const viewBox = svg.match(/viewBox="([\d\s.-]+)"/)?.[1];
    if (!viewBox) throw new Error(`Missing SVG viewBox: ${kind}`);
    let artwork = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<(title|desc)>[\s\S]*?<\/\1>/g, "");
    artwork = artwork.replace(/\bid="([\w-]+)"/g, `id="lr-${kind}-$1"`)
      .replace(/url\(#([\w-]+)\)/g, `url(#lr-${kind}-$1)`)
      .replace(/href="#([\w-]+)"/g, `href="#lr-${kind}-$1"`)
      .replace(/\b([a-z]+(?:-[a-z]+)+)=/g, (_, attribute) => attribute.replace(/-([a-z])/g, (__, letter) => letter.toUpperCase()) + "=");
    return `  ${kind === "work" ? "return" : `if (kind === "${kind}") return`} <svg className="lr-experience-poster" data-lr-poster="${kind}" viewBox="${viewBox}" aria-hidden="true" focusable="false">${artwork}</svg>;`;
  });
  const source = `// Generated by scripts/build-experience-posters.mjs from public/experience/*.svg.\n// Identity artwork retains the bitmap-derived study provenance in logo-outline.json.\nimport type { ExperienceStage } from "@/lib/experience";\n\nexport default function ExperiencePoster({ kind }: { kind: ExperienceStage }) {\n${branches.join("\n")}\n}\n`;
  const target = new URL("../src/components/experience/ExperiencePoster.tsx", import.meta.url);
  let previous;
  try { previous = readFileSync(target, "utf8"); } catch { /* First generation. */ }
  if (source !== previous) writeFileSync(target, source);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) buildExperiencePosters();
